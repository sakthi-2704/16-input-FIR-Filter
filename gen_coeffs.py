"""Generate Q1.15 low-pass FIR coefficients and write fir_coeffs.vh.

Design: N-tap linear-phase low-pass, Hamming window, designed with
scipy.signal.firwin. Cite this (scipy.signal.firwin) as the coefficient
source in the report.
"""
import numpy as np
from scipy import signal

N = 16          # number of taps
CUTOFF = 0.25   # normalised to Nyquist (0.25 -> fs/8)
CW = 16         # coefficient width (Q1.15)

h = signal.firwin(N, CUTOFF, window="hamming")
q = np.clip(np.round(h * 2**(CW - 1)), -2**(CW - 1), 2**(CW - 1) - 1).astype(int)

print("float coeffs :", np.round(h, 5))
print("Q1.15 coeffs :", [int(c) for c in q])
print("sum of coeffs:", q.sum(), f"(DC gain = {q.sum() / 2**(CW - 1):.4f})")

w, resp = signal.freqz(q / 2**(CW - 1), worN=2048)
mag = 20 * np.log10(np.maximum(np.abs(resp), 1e-12))
stop = w / np.pi > CUTOFF * 1.6
print(f"worst stopband attenuation (beyond 1.6x cutoff): {mag[stop].max():.1f} dB")

# Packed localparam: tap k occupies bits [k*CW +: CW]
words = [f"{CW}'h{int(c) & (2**CW - 1):04X}" for c in q]
with open("fir_coeffs.vh", "w") as f:
    f.write("// Auto-generated by gen_coeffs.py - do not edit by hand\n")
    f.write(f"// {N}-tap low-pass FIR, cutoff {CUTOFF} x Nyquist, Hamming window, Q1.{CW-1}\n")
    f.write(f"localparam [{N*CW-1}:0] COEFFS = {{\n")
    f.write(",\n".join("    " + w for w in reversed(words)))
    f.write("\n};\n")
print("wrote fir_coeffs.vh")
